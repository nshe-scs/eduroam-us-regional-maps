class Placemark:
    __slots__ = ("org", "loc", "lon", "lat", "description")

    def __init__(self, org: str, loc: str, lon: float, lat: float, description: str):
        self.org = org
        self.loc = loc
        self.lon = lon
        self.lat = lat
        self.description = description

    @property
    def key(self) -> Tuple[str, str, str, str]:
        """Identity of a service location: who, where by name, where on earth."""
        return (self.org, self.loc, coord(self.lon), coord(self.lat))

    @property
    def sort_key(self) -> Tuple:
        return (self.org.casefold(), self.loc.casefold(), self.lon, self.lat, self.description)

    def record(self) -> dict:
        """Full detail, for the changelog and the machine-readable log."""
        return {
            "org": self.org,
            "loc": self.loc,
            "lon": coord(self.lon),
            "lat": coord(self.lat),
            "description": self.description,
        }

    def inventory_record(self) -> dict:
        """
        Same identity, but the description reduced to a short digest.

        The description is only ever compared, never read back out, and the
        inventory is committed, so there is no reason to carry the full text.
        """
        return {
            "org": self.org,
            "loc": self.loc,
            "lon": coord(self.lon),
            "lat": coord(self.lat),
            "dhash": sha256_bytes(self.description.encode("utf-8"))[:16],
        }


LOC_NAME_RE = re.compile(r"<b>\s*Name:\s*</b>\s*(.*?)\s*(?:<br\s*/?>|$)", re.I | re.S)


def local_name(tag: str) -> str:
    return tag.rpartition("}")[2]


def find_child(element, name: str):
    for child in element:
        if local_name(child.tag) == name:
            return child
    return None


def child_text(element, name: str) -> str:
    child = find_child(element, name)
    return squash(child.text if child is not None else "")


def parse_source_kml(data: bytes) -> List[Placemark]:
    """Parse the upstream KML into a deduplicated, alphabetically sorted list."""
    try:
        root = ET.fromstring(data)
    except ET.ParseError as exc:
        raise SystemExit(f"Upstream map is not valid XML: {exc}")

    found: Dict[Tuple[str, str, str, str], Placemark] = {}
    duplicates = 0
    skipped = 0

    for element in root.iter():
        if local_name(element.tag) != "Placemark":
            continue
        point = find_child(element, "Point")
        if point is None:
            skipped += 1
            continue
        raw_coords = child_text(point, "coordinates")
        bits = [b for b in raw_coords.replace(" ", ",").split(",") if b]
        if len(bits) < 2:
            skipped += 1
            continue
        try:
            lon, lat = float(bits[0]), float(bits[1])
        except ValueError:
            skipped += 1
            continue
        if not (-180.0 <= lon <= 180.0 and -90.0 <= lat <= 90.0):
            skipped += 1
            continue

        org = squash(child_text(element, "name"))
        description = squash(child_text(element, "description"))
        match = LOC_NAME_RE.search(description)
        loc = squash(match.group(1)) if match else ""

        placemark = Placemark(org, loc, lon, lat, description)
        if placemark.key in found:
            duplicates += 1
            continue
        found[placemark.key] = placemark

    if duplicates:
        LOG.info("Dropped %d duplicate placemark(s) from the upstream map", duplicates)
    if skipped:
        LOG.info("Skipped %d placemark(s) with no usable point", skipped)

    return sorted(found.values(), key=lambda p: p.sort_key)


def fetch_source(cfg: dict, force: bool) -> Tuple[bytes, dict]:
    """
    Return (kml bytes, metadata).

    Uses a cached copy plus a conditional GET so that running several times a day
    costs at most one small 304 response -- and, inside min_refresh_seconds,
    no request at all.
    """
    cache_path = os.path.join(STATE_DIR, "source.kml")
    meta_path = os.path.join(STATE_DIR, "source.meta.json")
    meta = read_json(meta_path, {}) or {}
    url = cfg["source_url"]

    cached: Optional[bytes] = None
    if os.path.exists(cache_path) and meta.get("url") == url:
        try:
            with open(cache_path, "rb") as fh:
                cached = fh.read()
        except OSError:
            cached = None

    if cached and not force:
        age = time.time() - float(meta.get("fetched_at_epoch") or 0)
        if 0 <= age < float(cfg["min_refresh_seconds"]):
            LOG.info(
                "Using cached upstream map (%.0f min old, under the %.0f min refresh window)",
                age / 60.0,
                float(cfg["min_refresh_seconds"]) / 60.0,
            )
            return cached, meta

    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    if cached and not force:
        if meta.get("etag"):
            request.add_header("If-None-Match", meta["etag"])
        if meta.get("last_modified"):
            request.add_header("If-Modified-Since", meta["last_modified"])

    LOG.info("Checking %s for a newer map", url)
    try:
        with urllib.request.urlopen(request, timeout=cfg["http_timeout"]) as response:
            body = response.read()
            headers = response.headers
    except urllib.error.HTTPError as exc:
        if exc.code == 304 and cached:
            LOG.info("Upstream map unchanged (HTTP 304)")
            meta["fetched_at_epoch"] = time.time()
            meta["fetched_at"] = iso(utcnow())
            write_atomic(meta_path, json.dumps(meta, indent=2, sort_keys=True).encode())
            return cached, meta
        raise SystemExit(f"Failed to fetch {url}: HTTP {exc.code} {exc.reason}")
    except (urllib.error.URLError, OSError) as exc:
        raise SystemExit(f"Failed to fetch {url}: {exc}")

    if not body.strip():
        raise SystemExit("Upstream map came back empty -- refusing to touch the published maps.")

    digest = sha256_bytes(body)
    unchanged = digest == meta.get("sha256")
    meta = {
        "url": url,
        "sha256": digest,
        "bytes": len(body),
        "etag": headers.get("ETag") or "",
        "last_modified": headers.get("Last-Modified") or "",
        "fetched_at": iso(utcnow()),
        "fetched_at_epoch": time.time(),
    }
    write_atomic(cache_path, body)
    write_atomic(meta_path, json.dumps(meta, indent=2, sort_keys=True).encode())
    LOG.info(
        "Downloaded %.1f KiB (%s)",
        len(body) / 1024.0,
        "identical to the cached copy" if unchanged else "content changed",
    )
    return body, meta


