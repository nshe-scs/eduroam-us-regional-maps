STYLE_ID = "eduroam"


def build_kml(
    region: Region,
    placemarks: Sequence[Placemark],
    icon_href: str = "",
    attribution: str = "",
) -> str:
    """
    Render a region's KML.

    Deliberately contains no timestamps or other volatile content: identical
    input always produces a byte-identical file, which is what lets the job
    publish only the regions that really changed.

    With no icon_href the placemarks carry no style and the viewer draws its own
    default marker, so the output depends on nothing but this program.
    """
    icon_href = (icon_href or "").strip()
    # Sorted here rather than relying on the caller, so the guarantee holds for
    # any input: alphabetical output is what keeps the published files diffable.
    placemarks = sorted(placemarks, key=lambda p: p.sort_key)
    out: List[str] = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<kml xmlns="http://www.opengis.net/kml/2.2">',
        "  <Document>",
        f"    <name>eduroam \u2014 {xml_text(region.name)}</name>",
        "    <description>"
        + cdata(
            f"{len(placemarks)} eduroam service location"
            f"{'' if len(placemarks) == 1 else 's'} in {region.name}."
            + (f"<br><br>{attribution}" if attribution else "")
        )
        + "</description>",
        "    <open>1</open>",
    ]
    if icon_href:
        out.extend(
            [
                f'    <Style id="{STYLE_ID}">',
                "      <IconStyle>",
                f"        <Icon><href>{xml_text(icon_href)}</href></Icon>",
                "      </IconStyle>",
                "    </Style>",
            ]
        )
    for placemark in placemarks:
        out.extend(
            [
                "    <Placemark>",
                f"      <name>{xml_text(placemark.org)}</name>",
            ]
        )
        if icon_href:
            out.append(f"      <styleUrl>#{STYLE_ID}</styleUrl>")
        out.extend(
            [
                f"      <description>{cdata(placemark.description)}</description>",
                "      <Point>",
                f"        <coordinates>{coord(placemark.lon)},{coord(placemark.lat)},0</coordinates>",
                "      </Point>",
                "    </Placemark>",
            ]
        )
    out.extend(["  </Document>", "</kml>", ""])
    return "\n".join(out)


