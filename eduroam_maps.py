class Region:
    def __init__(self, code: str, name: str, path: str, boundary: Boundary, digest: str):
        self.code = code
        self.name = name
        self.path = path
        self.boundary = boundary
        self.digest = digest

    @property
    def filename(self) -> str:
        return f"eduroam_{self.code}.kml"


# A region file is "<code>.geojson" (or ".json"); the stem is the region code.
REGION_FILE_RE = re.compile(r"^(?P<code>[A-Za-z0-9][A-Za-z0-9_-]*)\.(?:geo)?json$")

NAME_KEYS = ("NAME", "name", "Name", "STATE_NAME", "NAME_1", "region", "REGION")


def region_display_name(data: dict, code: str) -> str:
    """Pick a human readable name out of the GeoJSON, else fall back to the code."""
    for key in NAME_KEYS:
        value = data.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    features = data.get("features") or ([data] if data.get("type") == "Feature" else [])
    for feature in features:
        props = (feature or {}).get("properties") or {}
        for key in NAME_KEYS:
            value = props.get(key)
            if isinstance(value, str) and value.strip():
                return value.strip()
    return code.upper()


def load_regions(regions_dir: str) -> List[Region]:
    if not os.path.isdir(regions_dir):
        raise SystemExit(f"No regions directory at {regions_dir!r} -- nothing to do.")

    regions: Dict[str, Region] = {}
    for entry in sorted(os.listdir(regions_dir)):
        path = os.path.join(regions_dir, entry)
        if not os.path.isfile(path) or entry.startswith("."):
            continue
        match = REGION_FILE_RE.match(entry)
        if not match:
            LOG.debug("Ignoring %s (not a region file)", entry)
            continue
        code = match.group("code").lower()

        try:
            with open(path, "rb") as fh:
                raw = fh.read()
            data = json.loads(raw.decode("utf-8"))
        except (OSError, ValueError) as exc:
            LOG.warning("Skipping region %r: cannot read %s (%s)", code, entry, exc)
            continue

        boundary = Boundary.from_geojson(data)
        if not boundary:
            LOG.warning("Skipping region %r: %s has no polygon geometry", code, entry)
            continue
        if code in regions:
            LOG.warning("Skipping duplicate region file %s (%r already loaded)", entry, code)
            continue

        regions[code] = Region(
            code=code,
            name=region_display_name(data, code),
            path=path,
            boundary=boundary,
            digest=sha256_bytes(raw),
        )

    if not regions:
        raise SystemExit(f"No usable region files found in {regions_dir!r}.")
    return [regions[code] for code in sorted(regions)]


