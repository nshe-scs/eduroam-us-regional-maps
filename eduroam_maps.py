def _label(record: dict) -> str:
    return f"{record['org']} \u2014 {record['loc']}" if record.get("loc") else record["org"]


def render_change_entry(stamp: str, diffs: List[RegionDiff]) -> str:
    """
    Render one dated changelog entry.

    Regions seen for the first time are recorded as a one-line baseline rather
    than thousands of "added" lines, so the very first run doesn't produce a
    changelog nobody can read.
    """
    baselines = sorted(
        (d for d in diffs if d.first_run and d.count),
        key=lambda d: d.region.name.casefold(),
    )
    changed = sorted(
        (d for d in diffs if d.locations_changed and not d.first_run),
        key=lambda d: d.region.name.casefold(),
    )
    if not baselines and not changed:
        return ""

    added = sum(len(d.added) for d in changed)
    removed = sum(len(d.removed) for d in changed)
    moved = sum(len(d.moved) for d in changed)

    bits = []
    if added:
        bits.append(f"{added} added")
    if removed:
        bits.append(f"{removed} removed")
    if moved:
        bits.append(f"{moved} moved")

    lines = [f"## {stamp}", ""]
    if bits:
        lines.extend([f"{', '.join(bits)} across {len(changed)} region(s).", ""])

    for diff in changed:
        lines.extend([f"### {diff.region.name} \u2014 {diff.previous_count} \u2192 {diff.count}", ""])
        for record in diff.added:
            lines.append(f"- **added** {_label(record)} `({record['lat']}, {record['lon']})`")
        for record in diff.removed:
            lines.append(f"- **removed** {_label(record)} `({record['lat']}, {record['lon']})`")
        for record in diff.moved:
            lines.append(
                f"- **moved** {_label(record)} "
                f"`({record['from']['lat']}, {record['from']['lon']})` \u2192 "
                f"`({record['to']['lat']}, {record['to']['lon']})`"
            )
        lines.append("")

    if baselines:
        total = sum(d.count for d in baselines)
        lines.extend(
            [
                f"### Baseline recorded for {len(baselines)} region(s), {total:,} location(s)",
                "",
                "Locations present when the region was first tracked; individual "
                "additions are listed from the next run onwards.",
                "",
            ]
        )
        for diff in baselines:
            lines.append(f"- {diff.region.name}: {diff.count:,}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


CHANGELOG_HEADER = (
    "# eduroam service location changelog\n"
    "\n"
    "Newest first. Each entry lists the service locations added to, removed from "
    "or moved within a region since the previous run.\n"
)


def update_changelog(path: str, entry: str, max_entries: int) -> str:
    existing = ""
    try:
        with open(path, encoding="utf-8") as fh:
            existing = fh.read()
    except OSError:
        pass

    body = existing.split("\n## ", 1)
    previous_entries = ("## " + body[1]) if len(body) > 1 else ""
    entries = [e for e in re.split(r"(?m)^(?=## )", previous_entries) if e.strip()]
    if entry:
        entries.insert(0, entry.rstrip() + "\n")
    if max_entries > 0:
        entries = entries[:max_entries]
    return CHANGELOG_HEADER + "\n" + "\n".join(e.rstrip() + "\n" for e in entries)


