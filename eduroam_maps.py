# geometry -- point in polygon, no third-party libraries
# --------------------------------------------------------------------------

class Ring:
    """A single closed linear ring with a cached bounding box."""

    __slots__ = ("points", "minx", "miny", "maxx", "maxy")

    def __init__(self, raw: Sequence[Sequence[float]]):
        pts = [(float(p[0]), float(p[1])) for p in raw]
        if pts and pts[0] != pts[-1]:
            pts.append(pts[0])
        self.points = pts
        xs = [p[0] for p in pts]
        ys = [p[1] for p in pts]
        self.minx, self.maxx = (min(xs), max(xs)) if xs else (0.0, 0.0)
        self.miny, self.maxy = (min(ys), max(ys)) if ys else (0.0, 0.0)

    def contains(self, x: float, y: float) -> bool:
        if x < self.minx or x > self.maxx or y < self.miny or y > self.maxy:
            return False
        pts = self.points
        inside = False
        x1, y1 = pts[0]
        for x2, y2 in pts[1:]:
            if (y1 > y) != (y2 > y):
                if x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
                    inside = not inside
            x1, y1 = x2, y2
        return inside


class Boundary:
    """One or more polygons (with holes) loaded from a GeoJSON file."""

    def __init__(self, parts: List[Tuple[Ring, List[Ring]]]):
        self.parts = parts
        if parts:
            self.minx = min(p[0].minx for p in parts)
            self.miny = min(p[0].miny for p in parts)
            self.maxx = max(p[0].maxx for p in parts)
            self.maxy = max(p[0].maxy for p in parts)
        else:
            self.minx = self.miny = self.maxx = self.maxy = 0.0

    def __bool__(self) -> bool:
        return bool(self.parts)

    def contains(self, x: float, y: float) -> bool:
        if not self.parts:
            return False
        if x < self.minx or x > self.maxx or y < self.miny or y > self.maxy:
            return False
        for exterior, holes in self.parts:
            if exterior.contains(x, y) and not any(h.contains(x, y) for h in holes):
                return True
        return False

    @staticmethod
    def _polygons(geom: dict) -> Iterable[Sequence]:
        kind = (geom or {}).get("type")
        coords = (geom or {}).get("coordinates") or []
        if kind == "Polygon":
            yield coords
        elif kind == "MultiPolygon":
            for poly in coords:
                yield poly
        elif kind == "GeometryCollection":
            for sub in (geom.get("geometries") or []):
                yield from Boundary._polygons(sub)

    @classmethod
    def from_geojson(cls, data: dict) -> "Boundary":
        kind = data.get("type")
        if kind == "FeatureCollection":
            geoms = [(f or {}).get("geometry") for f in data.get("features") or []]
        elif kind == "Feature":
            geoms = [data.get("geometry")]
        else:
            geoms = [data]
        parts: List[Tuple[Ring, List[Ring]]] = []
        for geom in geoms:
            for poly in cls._polygons(geom):
                if poly:
                    parts.append((Ring(poly[0]), [Ring(r) for r in poly[1:]]))
        return cls(parts)


