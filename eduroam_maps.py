def load_config() -> dict:
    """
    Merge config.json over the defaults.

    A missing file is fine -- the defaults are usable. A malformed one is not:
    silently falling back would run the job with the wrong publish target and
    the wrong attribution, which is worse than not running at all.
    """
    if not os.path.exists(CONFIG_PATH):
        LOG.info("No config at %s; using defaults", CONFIG_PATH)
        return dict(DEFAULT_CONFIG)
    try:
        with open(CONFIG_PATH, encoding="utf-8") as fh:
            user = json.load(fh)
    except ValueError as exc:
        raise SystemExit(f"{CONFIG_PATH} is not valid JSON: {exc}")
    except OSError as exc:
        raise SystemExit(f"Cannot read {CONFIG_PATH}: {exc}")
    if not isinstance(user, dict):
        raise SystemExit(f"{CONFIG_PATH} must contain a JSON object.")
    return deep_merge(DEFAULT_CONFIG, user)


def clip_to_regions(
    regions: Sequence[Region], placemarks: Sequence[Placemark]
) -> Tuple[Dict[str, List[Placemark]], int, int]:
    """Assign placemarks to regions. Returns (per region, assigned, unassigned)."""
    per_region: Dict[str, List[Placemark]] = {}
    matched: set = set()
    for region in regions:
        hits = [p for p in placemarks if region.boundary.contains(p.lon, p.lat)]
        per_region[region.code] = hits
        matched.update(p.key for p in hits)
        LOG.debug("%-6s %-28s %5d", region.code, region.name, len(hits))

    # Regions may overlap, so count distinct locations rather than summing the
    # per-region totals.
    assigned = len(matched)
    unassigned = len(placemarks) - assigned
    if unassigned:
        LOG.info(
            "%d location(s) fall outside every configured region "
            "(overseas entries, or a territory with no boundary file)",
            unassigned,
        )
    return per_region, assigned, unassigned


def enforce_guards(
    cfg: dict, total_upstream: int, assigned: int, previous_regions: dict, force: bool
) -> None:
    """Refuse to go any further if the upstream map looks broken."""
    if force:
        return
    if total_upstream < int(cfg["min_placemarks"]):
        raise SystemExit(
            f"Upstream map only has {total_upstream} locations, below the "
            f"min_placemarks guard of {cfg['min_placemarks']} -- refusing to publish. "
            "Re-run with --force to do it anyway."
        )
    known_before = sum(int(r.get("count", 0)) for r in previous_regions.values())
    if not known_before:
        return
    ratio = (known_before - assigned) / known_before
    if ratio > float(cfg["max_delete_ratio"]):
        raise SystemExit(
            f"Location count fell from {known_before} to {assigned} "
            f"({ratio:.0%} lost), above the max_delete_ratio guard of "
            f"{float(cfg['max_delete_ratio']):.0%} -- refusing to publish. "
            "Re-run with --force to do it anyway."
        )


def build_region_maps(
    cfg: dict,
    regions: Sequence[Region],
    per_region: Dict[str, List[Placemark]],
    previous_regions: Dict[str, dict],
    force: bool,
    dry_run: bool,
) -> Tuple[List[RegionDiff], Dict[str, dict], Dict[str, Optional[str]], List[str]]:
    """
    Diff each region against the inventory and rebuild the ones that moved.

    Returns (diffs, next inventory, files to publish, codes rebuilt).
    """
    regenerate_on_any = str(cfg.get("regenerate_on", "locations")).lower() == "any"
    icon = cfg.get("placemark_icon_url", "")
    attribution = attribution_for_kml(cfg)
    attribution_sha = attribution_digest(cfg)

    diffs: List[RegionDiff] = []
    inventory: Dict[str, dict] = {}
    changed: Dict[str, Optional[str]] = {}
    rebuilt: List[str] = []

    for region in regions:
        hits = per_region[region.code]
        previous = previous_regions.get(region.code) or {}
        diff = RegionDiff(region, previous, hits)
        diffs.append(diff)

        output_path = os.path.join(OUTPUT_DIR, region.filename)
        first_time = not previous
        missing_output = not os.path.exists(output_path)
        boundary_changed = previous.get("boundary_sha256") != region.digest
        name_changed = previous.get("name") != region.name
        attribution_changed = not first_time and previous.get("attribution_sha256") != attribution_sha

        if (
            force
            or first_time
            or missing_output
            or boundary_changed
            or name_changed
            or attribution_changed
            or diff.locations_changed
            or (regenerate_on_any and diff.anything_changed)
        ):
            kml = build_kml(region, hits, icon, attribution)
            if not dry_run:
                write_text_if_changed(output_path, kml)
            rebuilt.append(region.code)
            # Queued even when the local file was already byte-identical, so
            # that an interrupted publish is retried: the inventory and the
            # output only ever advance together.
            changed[region.filename] = kml
            LOG.info(
                "%s %s (%s, %d locations)",
                "[dry-run] would rebuild" if dry_run else "Rebuilt",
                region.filename,
                "forced" if force
                else "new region" if first_time
                else "new output" if missing_output
                else "boundary changed" if boundary_changed
                else "region renamed" if name_changed
                else "attribution changed" if attribution_changed
                else "locations changed",
                len(hits),
            )
        elif diff.metadata_changed:
            LOG.info(
                "%s: %d metadata-only change(s) upstream, not republished "
                "(regenerate_on=locations)",
                region.code,
                diff.metadata_changed,
            )
            inventory[region.code] = previous

        if region.code in inventory:
            continue
        # The inventory describes what is published, not what is upstream. A
        # region that was not rebuilt still has its old description text in the
        # published KML, so carry its entry forward untouched; otherwise
        # metadata churn alone would rewrite the inventory every run.
        inventory[region.code] = {
            "name": region.name,
            "count": len(hits),
            "boundary_sha256": region.digest,
            "attribution_sha256": attribution_sha,
            "placemarks": [p.inventory_record() for p in hits],
        }

    return diffs, inventory, changed, rebuilt


def retire_regions(
    regions: Sequence[Region],
    previous_regions: Dict[str, dict],
    changed: Dict[str, Optional[str]],
    dry_run: bool,
) -> None:
    """Withdraw maps whose region file has been deleted."""
    live = {r.code for r in regions}
    for code in sorted(set(previous_regions) - live):
        filename = f"eduroam_{code}.kml"
        LOG.warning("Region %r no longer configured -- retiring %s", code, filename)
        changed[filename] = None
        path = os.path.join(OUTPUT_DIR, filename)
        if os.path.exists(path) and not dry_run:
            os.remove(path)


def setup_logging(verbose: bool) -> None:
    os.makedirs(STATE_DIR, exist_ok=True)
    LOG.setLevel(logging.DEBUG)

    file_handler = logging.FileHandler(os.path.join(STATE_DIR, "run.log"), encoding="utf-8")
    file_handler.setFormatter(logging.Formatter("%(asctime)s %(levelname)-7s %(message)s"))
    file_handler.setLevel(logging.DEBUG)
    LOG.addHandler(file_handler)

    # A minimal cron environment can give us an ASCII console. Region names and
    # attribution text are user data, so degrade unrepresentable characters
    # rather than letting the job die on its own log output.
    for handle in (sys.stdout, sys.stderr):
        try:
            handle.reconfigure(errors="backslashreplace")
        except (AttributeError, ValueError, OSError):
            pass

    stream = logging.StreamHandler(sys.stderr)
    stream.setFormatter(logging.Formatter("%(levelname)-7s %(message)s"))
    stream.setLevel(logging.DEBUG if verbose else logging.WARNING)
    LOG.addHandler(stream)


def acquire_lock() -> "object":
    os.makedirs(STATE_DIR, exist_ok=True)
    handle = open(os.path.join(STATE_DIR, "run.lock"), "w")
    try:
        fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        raise SystemExit("Another run is already in progress; exiting.")
    handle.write(f"{os.getpid()}\n")
    handle.flush()
    return handle


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[1])
    parser.add_argument("-v", "--verbose", action="store_true", help="log progress to stderr")
    parser.add_argument("-f", "--force", action="store_true", help="re-download and rebuild everything")
    parser.add_argument("-n", "--dry-run", action="store_true", help="compute changes but write and publish nothing")
    args = parser.parse_args(argv)

    verbose = args.verbose or truthy_env("EDUROAM_VERBOSE")
    force = args.force or truthy_env("EDUROAM_FORCE")

    setup_logging(verbose)
    lock = acquire_lock()
    started = utcnow()
    LOG.info("=== run started %s (version %s) ===", iso(started), __version__)

    cfg = load_config()
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # ---- regions and source data -------------------------------------
    regions = load_regions(REGIONS_DIR)
    LOG.info("Loaded %d region(s): %s", len(regions), ", ".join(r.code for r in regions))

    source_bytes, source_meta = fetch_source(cfg, force)
    placemarks = parse_source_kml(source_bytes)
    LOG.info("Upstream map holds %d unique service location(s)", len(placemarks))

    inventory_path = os.path.join(STATE_DIR, "inventory.json")
    inventory = read_json(inventory_path, {}) or {}
    previous_regions: Dict[str, dict] = inventory.get("regions", {}) or {}

    per_region, assigned, unassigned = clip_to_regions(regions, placemarks)
    enforce_guards(cfg, len(placemarks), assigned, previous_regions, force)

    diffs, new_inventory_regions, changed_files, rebuilt = build_region_maps(
        cfg, regions, per_region, previous_regions, force, args.dry_run
    )
    retire_regions(regions, previous_regions, changed_files, args.dry_run)

    # ---- reports ------------------------------------------------------
    stamp_day = started.strftime("%Y-%m-%d")
    # Time included so that several runs on the same day stay distinguishable.
    entry = render_change_entry(started.strftime("%Y-%m-%d %H:%M UTC"), diffs)
    last_changed = stamp_day if entry else (inventory.get("last_changed") or "")

    publish_cfg = cfg["publish"]
    publish_state_path = os.path.join(STATE_DIR, "publish.json")
    publisher: Optional[PagesPublisher] = None
    publish_state = read_json(publish_state_path, {}) or {}
    site_url = str(publish_cfg.get("site_url") or "").strip() or publish_state.get("site_url", "")

    if publish_cfg.get("enabled") and not args.dry_run:
        token = resolve_token(publish_cfg)
        if not str(publish_cfg.get("repo") or "").strip():
            LOG.error("Publishing is enabled but publish.repo is not set. Skipping publish.")
        elif not token:
            LOG.error(
                "Publishing is enabled but no token was found (env %s). Skipping publish.",
                publish_cfg.get("token_env"),
            )
        else:
            try:
                publisher = PagesPublisher(publish_cfg, token, publish_state_path)
                if site_url:
                    # Already known from config or a previous run; a no-op run
                    # then costs zero GitHub API calls.
                    publisher.site_url = site_url
                else:
                    site_url = publisher.resolve_site()
            except RuntimeError as exc:
                LOG.error("Could not reach the Pages repository: %s", exc)
                publisher = None

    rows = [
        (region, len(per_region[region.code]),
         int(previous_regions[region.code]["count"]) if region.code in previous_regions else None)
        for region in regions
    ]
    leaderboard = render_leaderboard(rows, cfg, last_changed, iso(started), site_url, assigned)
    index_html = render_index_html(rows, cfg, last_changed, site_url, assigned)
    changelog = update_changelog(
        os.path.join(OUTPUT_DIR, CHANGELOG_NAME), entry, int(cfg["changelog_max_entries"])
    )

    if not args.dry_run:
        for name, content in (
            (LEADERBOARD_NAME, leaderboard),
            (INDEX_NAME, index_html),
            (CHANGELOG_NAME, changelog),
        ):
            if write_text_if_changed(os.path.join(OUTPUT_DIR, name), content):
                changed_files[name] = content
        # Stops GitHub Pages running the files through Jekyll.
        nojekyll = os.path.join(OUTPUT_DIR, NOJEKYLL_NAME)
        if not os.path.exists(nojekyll):
            write_atomic(nojekyll, b"")
            changed_files[NOJEKYLL_NAME] = ""
        elif not publish_state.get("bootstrapped"):
            changed_files[NOJEKYLL_NAME] = ""

    tracked = [d for d in diffs if not d.first_run]
    totals = {
        "added": sum(len(d.added) for d in tracked),
        "removed": sum(len(d.removed) for d in tracked),
        "moved": sum(len(d.moved) for d in tracked),
        "metadata_changed": sum(d.metadata_changed for d in diffs),
        "baselined_regions": sum(1 for d in diffs if d.first_run and d.count),
    }

    if entry and not args.dry_run:
        record = {
            "run": iso(started),
            "source_sha256": source_meta.get("sha256", ""),
            "totals": dict(totals, regions=len(regions), locations=assigned, unassigned=unassigned),
            "regions": {
                d.region.code: d.summary() for d in diffs if d.locations_changed
            },
        }
        jsonl_path = os.path.join(OUTPUT_DIR, CHANGES_JSONL)
        lines = []
        try:
            with open(jsonl_path, encoding="utf-8") as fh:
                lines = [ln for ln in fh.read().splitlines() if ln.strip()]
        except OSError:
            pass
        lines.append(json.dumps(record, sort_keys=True))
        cap = int(cfg["changes_max_entries"])
        if cap > 0:
            lines = lines[-cap:]
        body = "\n".join(lines) + "\n"
        write_atomic(jsonl_path, body.encode("utf-8"))
        changed_files[CHANGES_JSONL] = body

    # ---- publish ------------------------------------------------------
    published = 0
    if publisher and changed_files:
        try:
            commit = publisher.publish(changed_files)
            published = len(changed_files)
            site_url = publisher.site_url
            if commit:
                LOG.info("Committed %d file(s) as %s", published, commit[:10])
            LOG.info("Published at %s", site_url)
        except RuntimeError as exc:
            LOG.error("Publishing failed: %s", exc)
            LOG.error("Local files are up to date; the next run will retry the push.")
            published = -1
    elif publisher:
        LOG.info("Nothing changed -- repository left untouched")

    # ---- persist state -------------------------------------------------
    if not args.dry_run and published >= 0:
        # Data only. Anything that changes from run to run regardless of the
        # data belongs in last_run.json, so that a quiet day produces a
        # byte-identical inventory and therefore no commit.
        write_atomic(
            inventory_path,
            json.dumps(
                {
                    "version": __version__,
                    "last_changed": last_changed,
                    "regions": new_inventory_regions,
                },
                indent=1,
                sort_keys=True,
            ).encode(),
        )
        write_atomic(
            os.path.join(STATE_DIR, "last_run.json"),
            json.dumps(
                {
                    "generated": iso(started),
                    "source_sha256": source_meta.get("sha256", ""),
                    "locations": assigned,
                    "unassigned": unassigned,
                    "regions": len(regions),
                    "rebuilt": sorted(rebuilt),
                },
                indent=2,
                sort_keys=True,
            ).encode(),
        )

    # ---- summary --------------------------------------------------------
    summary = (
        f"{assigned:,} locations in {len(regions)} regions; "
        f"+{totals['added']} -{totals['removed']} ~{totals['moved']}"
    )
    if totals["baselined_regions"]:
        summary += f"; {totals['baselined_regions']} region(s) baselined"
    summary += f"; {len(rebuilt)} map(s) rebuilt"
    LOG.info("=== run finished: %s ===", summary)

    if args.dry_run:
        print(f"[dry-run] {summary}")
    elif entry or rebuilt or changed_files:
        print(f"eduroam maps updated: {summary}")
        if publisher and published > 0:
            print(f"Published {published} file(s) to {site_url}")
    elif verbose:
        print(f"No changes. {summary}")

    lock.close()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit:
        raise
    except KeyboardInterrupt:
        sys.exit(130)
    except Exception as exc:  # noqa: BLE001 - cron wants a readable failure
        LOG.exception("Unhandled error: %s", exc)
        print(f"eduroam_maps.py failed: {exc}", file=sys.stderr)
        sys.exit(1)
