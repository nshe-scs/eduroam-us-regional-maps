"""
eduroam_maps.py -- build per-region eduroam service location maps.

Downloads the public eduroam-US location map, clips it against a set of region
boundary files, and writes one KML per region into the output directory together
with a leaderboard, a changelog and a machine-readable log of what changed.

Only regions whose service locations actually changed are rewritten, so the
published files can be committed straight to a GitHub Pages repository. It can
also push to that repository itself over the GitHub API, for hosts with no
checkout to commit from; see the publish section of the config.

Runs unattended with no arguments, from GitHub Actions or from cron. Nothing but
the Python 3.8+ standard library is required.

Regions are configuration: add a GeoJSON polygon named <code>.geojson to the
regions/ directory to add one, delete the file to remove one. No code changes
are needed to add, modify, or remove regions.

See README.md for setup and layout.
"""

