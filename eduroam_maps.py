MD_LINK_RE = re.compile(r"\[([^\]]+)\]\((https?://[^)\s\"']+)\)")


def attr(value: str) -> str:
    """Escape a string for use inside a double-quoted HTML/XML attribute."""
    return xml_text(value).replace('"', "&quot;")


def markdown_links_to_html(text: str) -> str:
    """
    Render the tiny subset of Markdown allowed in attribution footnotes.

    Only [label](http(s)://...) becomes a link; everything else is escaped, so a
    footnote can never inject markup into the page.
    """
    out: List[str] = []
    pos = 0
    for match in MD_LINK_RE.finditer(text):
        out.append(xml_text(text[pos:match.start()]))
        out.append(f'<a href="{attr(match.group(2))}">{xml_text(match.group(1))}</a>')
        pos = match.end()
    out.append(xml_text(text[pos:]))
    return "".join(out)


def attribution_lines(cfg: dict) -> List[str]:
    """Publisher note first, then the standing footnotes, all as Markdown."""
    block = cfg.get("attribution") or {}
    lines = []
    publisher = str(block.get("publisher_note") or "").strip()
    if publisher:
        lines.append(publisher)
    for note in block.get("footnotes") or []:
        note = str(note or "").strip()
        if note:
            lines.append(note)
    return lines


def attribution_for_kml(cfg: dict) -> str:
    """The same attribution, as an HTML fragment for a KML <description>."""
    lines = attribution_lines(cfg)
    if not lines:
        return ""
    return "<br>".join(markdown_links_to_html(line) for line in lines)


def attribution_digest(cfg: dict) -> str:
    """Changing the attribution has to rebuild the maps that carry it."""
    return sha256_bytes(attribution_for_kml(cfg).encode("utf-8"))


def site_file_url(site_url: str, filename: str) -> str:
    if not site_url:
        return ""
    return site_url.rstrip("/") + "/" + filename


def ranked_rows(
    rows: List[Tuple[Region, int, Optional[int]]]
) -> List[Tuple[int, Region, int, str]]:
    """
    Sort regions by count then name, assigning equal ranks to ties.

    Shared by the Markdown and HTML leaderboards so the two can never drift.
    """
    ordered = sorted(rows, key=lambda r: (-r[1], r[0].name.casefold()))
    out = []
    rank = 0
    previous_count = None
    for index, (region, count, before) in enumerate(ordered, start=1):
        if count != previous_count:
            rank, previous_count = index, count
        out.append((rank, region, count, _delta(count, before)))
    return out


def _delta(count: int, before: Optional[int]) -> str:
    if before is None:
        return "new"
    if count > before:
        return f"+{count - before}"
    if count < before:
        return f"\u2212{before - count}"
    return "\u2013"


