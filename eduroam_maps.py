class RegionDiff:
    def __init__(self, region: Region, previous: dict, current: Sequence[Placemark]):
        self.region = region
        self.count = len(current)
        self.previous_count = int(previous.get("count", 0)) if previous else 0
        self.first_run = not previous

        old_records = {
            (r["org"], r["loc"], r["lon"], r["lat"]): r
            for r in (previous or {}).get("placemarks", [])
        }
        live = {p.key: p for p in current}
        new_records = {key: p.inventory_record() for key, p in live.items()}

        added_keys = sorted(set(new_records) - set(old_records))
        removed_keys = sorted(set(old_records) - set(new_records))

        # A location that kept its name but changed coordinates reads much
        # better as "moved" than as an unrelated add plus delete.
        added_by_name: Dict[Tuple[str, str], List[tuple]] = {}
        for key in added_keys:
            added_by_name.setdefault((key[0], key[1]), []).append(key)
        removed_by_name: Dict[Tuple[str, str], List[tuple]] = {}
        for key in removed_keys:
            removed_by_name.setdefault((key[0], key[1]), []).append(key)

        self.moved: List[dict] = []
        paired_added, paired_removed = set(), set()
        for name, olds in removed_by_name.items():
            news = added_by_name.get(name) or []
            if len(olds) == 1 and len(news) == 1:
                old_key, new_key = olds[0], news[0]
                paired_removed.add(old_key)
                paired_added.add(new_key)
                self.moved.append(
                    {
                        "org": name[0],
                        "loc": name[1],
                        "from": {"lon": old_key[2], "lat": old_key[3]},
                        "to": {"lon": new_key[2], "lat": new_key[3]},
                    }
                )
        self.moved.sort(key=lambda m: (m["org"].casefold(), m["loc"].casefold()))

        self.added = [live[k].record() for k in added_keys if k not in paired_added]
        self.removed = [
            {k2: v for k2, v in old_records[k].items() if k2 != "dhash"}
            for k in removed_keys
            if k not in paired_removed
        ]

        # Metadata-only edits (an AP count ticking over, say) are tracked but do
        # not, by default, count as a change worth republishing for.
        self.metadata_changed = sum(
            1
            for key, record in new_records.items()
            if key in old_records and old_records[key].get("dhash") != record["dhash"]
        )

    @property
    def locations_changed(self) -> bool:
        return bool(self.added or self.removed or self.moved)

    @property
    def anything_changed(self) -> bool:
        return self.locations_changed or bool(self.metadata_changed)

    def summary(self) -> dict:
        record = {
            "name": self.region.name,
            "count": self.count,
            "previous_count": self.previous_count,
            "metadata_changed": self.metadata_changed,
        }
        if self.first_run:
            # Don't dump every location on the very first run for a region;
            # record it as a baseline instead.
            record["baseline"] = True
            return record
        record.update({"added": self.added, "removed": self.removed, "moved": self.moved})
        return record


