class PagesPublisher:
    """
    Publishes the generated files to a GitHub Pages repository.

    Everything a run changes goes into a single commit via the Git data API, so
    the repository history is one commit per day of real change rather than one
    commit per file.
    """

    def __init__(self, cfg: dict, token: str, state_path: str):
        self.cfg = cfg
        self.token = token
        self.state_path = state_path
        self.state = read_json(state_path, {}) or {}

        repo = str(cfg.get("repo") or "").strip().strip("/")
        if repo.count("/") != 1 or not all(repo.split("/")):
            raise RuntimeError(f"publish.repo must look like 'owner/repo', got {repo!r}")
        self.owner, self.repo = repo.split("/")
        self.branch = str(cfg.get("branch") or "gh-pages").strip() or "gh-pages"
        self.subpath = str(cfg.get("path") or "").strip("/")
        self.site_url = str(cfg.get("site_url") or "").strip() or self.state.get("site_url", "")

    # -- low level -------------------------------------------------------
    def _api(
        self,
        method: str,
        path: str,
        payload: Optional[dict] = None,
        allow: Tuple[int, ...] = (),
    ) -> Tuple[int, dict]:
        data = json.dumps(payload).encode("utf-8") if payload is not None else None
        request = urllib.request.Request(
            f"{GITHUB_API}{path}",
            data=data,
            method=method,
            headers={
                "Authorization": f"Bearer {self.token}",
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
                "Content-Type": "application/json",
                "User-Agent": USER_AGENT,
            },
        )
        last: Optional[Exception] = None
        for attempt in range(3):
            try:
                with urllib.request.urlopen(request, timeout=self.cfg.get("http_timeout", 60)) as response:
                    body = response.read().decode("utf-8") or "{}"
                    return response.status, (json.loads(body) if body.strip() else {})
            except urllib.error.HTTPError as exc:
                detail = exc.read().decode("utf-8", "replace")[:400]
                if exc.code in allow:
                    return exc.code, {"message": detail}
                # Only transient classes are retried; 4xx will fail the same
                # way on a second attempt.
                if exc.code in (429, 500, 502, 503) and attempt < 2:
                    delay = 2 ** attempt * 3
                    LOG.warning("GitHub API %s (attempt %d), retrying in %ds", exc.code, attempt + 1, delay)
                    time.sleep(delay)
                    last = exc
                    continue
                raise RuntimeError(f"GitHub API {method} {path} failed: HTTP {exc.code} {detail}")
            except (urllib.error.URLError, OSError, ValueError) as exc:
                if attempt < 2:
                    time.sleep(2 ** attempt * 3)
                    last = exc
                    continue
                raise RuntimeError(f"GitHub API {method} {path} failed: {exc}")
        raise RuntimeError(f"GitHub API {method} {path} failed: {last}")

    def _save_state(self, **fields) -> None:
        self.state.update(fields)
        self.state["updated_at"] = iso(utcnow())
        write_atomic(self.state_path, json.dumps(self.state, indent=2, sort_keys=True).encode())

    def _repo_path(self, filename: str) -> str:
        return posixpath.join(self.subpath, filename) if self.subpath else filename

    # -- pages -----------------------------------------------------------
    def resolve_site(self) -> str:
        """Find (or turn on) the Pages site and work out its public URL."""
        if self.subpath not in ("", "docs"):
            LOG.warning(
                "GitHub Pages only serves from the repository root or /docs; "
                "publish.path=%r will be committed but not served",
                self.subpath,
            )

        status, info = self._api("GET", f"/repos/{self.owner}/{self.repo}/pages", allow=(403, 404))
        if status == 200 and info.get("html_url"):
            url = info["html_url"]
        elif status == 404 and self.cfg.get("enable_pages", True):
            LOG.info("GitHub Pages is not enabled on %s/%s -- turning it on", self.owner, self.repo)
            source = {"branch": self.branch, "path": f"/{self.subpath}" if self.subpath else "/"}
            status, info = self._api(
                "POST",
                f"/repos/{self.owner}/{self.repo}/pages",
                {"source": source},
                allow=(403, 404, 409, 422),
            )
            if status in (201, 204) and info.get("html_url"):
                url = info["html_url"]
            else:
                LOG.warning(
                    "Could not enable Pages automatically (%s). Enable it once by hand: "
                    "repository Settings -> Pages -> deploy from branch %r, folder %r.",
                    status,
                    self.branch,
                    f"/{self.subpath}" if self.subpath else "/",
                )
                url = self._guess_site_url()
        else:
            url = self._guess_site_url()

        self.site_url = url.rstrip("/") + "/"
        self._save_state(site_url=self.site_url)
        return self.site_url

    def _guess_site_url(self) -> str:
        owner = self.owner.lower()
        if self.repo.lower() in (f"{owner}.github.io", f"{owner}.github.com"):
            return f"https://{owner}.github.io/"
        return f"https://{owner}.github.io/{self.repo}/"

    # -- committing ------------------------------------------------------
    def _head(self) -> Tuple[Optional[str], Optional[str]]:
        status, ref = self._api(
            "GET",
            f"/repos/{self.owner}/{self.repo}/git/ref/heads/{self.branch}",
            allow=(404, 409),
        )
        if status != 200:
            LOG.info("Branch %r does not exist yet; creating it", self.branch)
            return None, None
        commit_sha = (ref.get("object") or {}).get("sha")
        if not commit_sha:
            return None, None
        _, commit = self._api("GET", f"/repos/{self.owner}/{self.repo}/git/commits/{commit_sha}")
        return commit_sha, (commit.get("tree") or {}).get("sha")

    def _existing_paths(self, tree_sha: str) -> set:
        status, tree = self._api(
            "GET",
            f"/repos/{self.owner}/{self.repo}/git/trees/{tree_sha}?recursive=1",
            allow=(404, 422),
        )
        if status != 200:
            return set()
        return {e.get("path") for e in tree.get("tree") or [] if e.get("type") == "blob"}

    def publish(self, updates: Dict[str, Optional[str]]) -> Optional[str]:
        """updates maps filename -> content, or filename -> None to delete."""
        if not updates:
            return None

        base_commit, base_tree = self._head()
        deletions = {n for n, c in updates.items() if c is None}
        present: set = set()
        if deletions and base_tree:
            present = self._existing_paths(base_tree)

        entries: List[dict] = []
        for name in sorted(updates):
            content = updates[name]
            repo_path = self._repo_path(name)
            if content is None:
                # Asking to delete something that was never committed is an error,
                # so only send deletions we can see in the current tree.
                if repo_path in present:
                    entries.append({"path": repo_path, "mode": "100644", "type": "blob", "sha": None})
                else:
                    LOG.debug("Skipping delete of %s (not in the published tree)", repo_path)
                continue
            _, blob = self._api(
                "POST",
                f"/repos/{self.owner}/{self.repo}/git/blobs",
                {
                    "content": base64.b64encode(content.encode("utf-8")).decode("ascii"),
                    "encoding": "base64",
                },
            )
            entries.append({"path": repo_path, "mode": "100644", "type": "blob", "sha": blob["sha"]})

        if not entries:
            return None

        LOG.info("Committing %d change(s) to %s/%s@%s", len(entries), self.owner, self.repo, self.branch)
        payload: Dict[str, object] = {"tree": entries}
        if base_tree:
            payload["base_tree"] = base_tree
        _, tree = self._api("POST", f"/repos/{self.owner}/{self.repo}/git/trees", payload)

        author = {
            "name": self.cfg.get("author_name") or "github-actions[bot]",
            "email": self.cfg.get("author_email") or "41898282+github-actions[bot]@users.noreply.github.com",
            "date": iso(utcnow()),
        }
        _, commit = self._api(
            "POST",
            f"/repos/{self.owner}/{self.repo}/git/commits",
            {
                "message": self.cfg.get("commit_message") or "Update eduroam service location maps",
                "tree": tree["sha"],
                "parents": [base_commit] if base_commit else [],
                "author": author,
                "committer": author,
            },
        )
        commit_sha = commit["sha"]

        if base_commit:
            self._api(
                "PATCH",
                f"/repos/{self.owner}/{self.repo}/git/refs/heads/{self.branch}",
                {"sha": commit_sha, "force": False},
            )
        else:
            self._api(
                "POST",
                f"/repos/{self.owner}/{self.repo}/git/refs",
                {"ref": f"refs/heads/{self.branch}", "sha": commit_sha},
            )

        self._save_state(last_commit=commit_sha, bootstrapped=True)
        return commit_sha


def resolve_token(publish_cfg: dict) -> str:
    token = os.environ.get(publish_cfg.get("token_env") or "GITHUB_TOKEN", "").strip()
    if token:
        return token
    path = publish_cfg.get("token_file") or ""
    if path:
        path = os.path.expanduser(path)
        try:
            with open(path, encoding="utf-8") as fh:
                return fh.read().strip()
        except OSError as exc:
            LOG.error("Cannot read token file %s: %s", path, exc)
    return ""


